    f.write("    def _engine(self):\n")
    f.write("        from vnpy.temporal_intelligence_ai.engine.validation_engine import ValidationEngine\n")
    f.write("        return ValidationEngine()\n")
    f.write("    def _rec(self, rid, pred, real=None, realized=False, horizon=5):\n")
    f.write("        from vnpy.temporal_intelligence_ai.model.validation_model import ValidationRecord\n")
    f.write("        return ValidationRecord(record_id=rid, predicted=pred,\n")
    f.write("                                realized=real, is_realized=realized, horizon_bars=horizon)\n")
