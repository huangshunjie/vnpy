    f.write("    def test_summary_keys(self):\n")
    f.write("        eng = self._engine(); rets = self._rets(200)\n")
    f.write("        eng.update_series(prices=self._prices(rets), returns=rets)\n")
    f.write("        eng.detect()\n")
    f.write("        summ = eng.get_summary()\n")
    f.write("        assert all(k in summ for k in\n")
    f.write("                   ('transition_prob','transition_confidence','is_transitioning','current_regime'))\n")
