    f.write("        eng = self._engine()\n")
    f.write("        eng.submit_prediction(self._rec('r1', pred=0.5))\n")
    f.write("        assert eng.validate().metrics.n_realized == 0\n")
    f.write("    def test_realized_included(self):\n")
    f.write("        import random as rr; rr.seed(42)\n")
    f.write("        eng = self._engine()\n")
    f.write("        for i in range(20):\n")
    f.write("            p = rr.gauss(0, 1)\n")
    f.write("            eng.submit_prediction(self._rec(f'r{i}', p, real=p+rr.gauss(0,0.1), realized=True))\n")
