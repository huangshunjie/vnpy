import pathlib
P = pathlib.Path(r"c:\Users\11229\Documents\GitHub\vnpy\tests\test_temporal_intelligence.py")
with open(P, "a", encoding="utf-8") as f:
    f.write("\n\nclass TestTransitionEngine:\n")
    f.write("    def _rets(self, n=200, mean=0.001, vol=0.02, seed=3):\n")
    f.write("        import random as rr; rr.seed(seed)\n")
    f.write("        return [rr.gauss(mean, vol) for _ in range(n)]\n")
    f.write("    def _prices(self, rets, p0=100.0):\n")
    f.write("        ps = [p0]\n")
    f.write("        for r in rets: ps.append(ps[-1] * (1 + r))\n")
    f.write("        return ps\n")
    f.write("    def _engine(self):\n")
    f.write("        from vnpy.temporal_intelligence_ai.engine.transition_engine import TransitionEngine\n")
    f.write("        eng = TransitionEngine()\n")
    f.write("        eng.configure(regime_fast=10, regime_slow=40, regime_thresh=1.5,\n")
    f.write("                      vol_short=10, vol_long=40, vol_ratio=1.5,\n")
    f.write("                      liq_short=10, liq_long=40, liq_thresh=1.3)\n")
    f.write("        return eng\n")
    f.write("    def test_detect_returns_state(self):\n")
    f.write("        eng = self._engine(); rets = self._rets(200)\n")
    f.write("        eng.update_series(prices=self._prices(rets), returns=rets)\n")
    f.write("        assert eng.detect() is not None\n")
    f.write("    def test_prob_range(self):\n")
    f.write("        eng = self._engine(); rets = self._rets(200)\n")
    f.write("        eng.update_series(prices=self._prices(rets), returns=rets)\n")
    f.write("        s = eng.detect()\n")
    f.write("        assert 0.0 <= s.transition_prob <= 1.0\n")
    f.write("        assert 0.0 <= s.transition_confidence <= 1.0\n")
    f.write("    def test_regime_probs_sum(self):\n")
    f.write("        eng = self._engine(); rets = self._rets(200)\n")
    f.write("        eng.update_series(prices=self._prices(rets), returns=rets)\n")
    f.write("        total = sum(eng.detect().regime_probs.probabilities.values())\n")
    f.write("        assert total == pytest.approx(1.0, abs=0.02)\n")
    f.write("    def test_context_preserved(self):\n")
    f.write("        from vnpy.temporal_intelligence_ai.constant import RegimeType, CyclePhase\n")
    f.write("        eng = self._engine()\n")
    f.write("        eng.set_context(regime=RegimeType.BEAR_VOLATILE, phase=CyclePhase.CONTRACTION,\n")
    f.write("                        current_vol=0.40, current_trend=-0.15)\n")
    f.write("        rets = self._rets(200)\n")
    f.write("        eng.update_series(prices=self._prices(rets), returns=rets)\n")
